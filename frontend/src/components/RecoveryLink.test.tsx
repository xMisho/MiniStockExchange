import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import { RecoveryLink } from './RecoveryLink'
import * as api from '../api/auth'
const restore = vi.fn()
vi.mock('../api/auth')
vi.mock('../auth/authState', () => ({ useAuth: () => ({ restore }) }))
beforeEach(() => { vi.resetAllMocks(); restore.mockResolvedValue(undefined) })
afterEach(() => { cleanup(); window.history.replaceState(null, '', '#/markets') })
it('removes the token from history, validates confirmation, and resets only on explicit submit', async () => {
  window.history.replaceState(null, '', '#/reset-password?token=private-token')
  vi.mocked(api.resetPassword).mockResolvedValue(undefined)
  render(<RecoveryLink />)
  expect(window.location.hash).toBe('#/markets')
  expect(api.resetPassword).not.toHaveBeenCalled()
  fireEvent.change(screen.getByLabelText('New password'), { target: { value: 'NewPassword123456!' } })
  fireEvent.change(screen.getByLabelText('Confirm new password'), { target: { value: 'DifferentPassword123!' } })
  fireEvent.click(screen.getByRole('button', { name: 'Change password' }))
  expect(screen.getByRole('alert').textContent).toBe('Passwords do not match.')
  expect(api.resetPassword).not.toHaveBeenCalled()
  fireEvent.change(screen.getByLabelText('Confirm new password'), { target: { value: 'NewPassword123456!' } })
  fireEvent.click(screen.getByRole('button', { name: 'Change password' }))
  expect(await screen.findByText(/Password changed/)).toBeTruthy()
  expect(api.resetPassword).toHaveBeenCalledExactlyOnceWith('private-token', 'NewPassword123456!')
  expect(screen.queryByLabelText('New password')).toBeNull()
  await waitFor(() => expect(restore).toHaveBeenCalledOnce())
})
it('does not consume a verification link just by opening it', async () => {
  window.history.replaceState(null, '', '#/verify-email?token=verification-token')
  vi.mocked(api.verifyEmail).mockResolvedValue(undefined)
  render(<RecoveryLink />)
  expect(api.verifyEmail).not.toHaveBeenCalled()
  fireEvent.click(screen.getByRole('button', { name: 'Verify email' }))
  expect(await screen.findByText(/Email verified/)).toBeTruthy()
  expect(api.verifyEmail).toHaveBeenCalledExactlyOnceWith('verification-token')
})
it('shows expired or reused links without automatically retrying', async () => {
  window.history.replaceState(null, '', '#/verify-email?token=old-token')
  vi.mocked(api.verifyEmail).mockRejectedValue(new Error('This link is invalid, expired, or already used. Request a new one.'))
  render(<RecoveryLink />)
  fireEvent.click(screen.getByRole('button', { name: 'Verify email' }))
  expect(await screen.findByRole('alert')).toHaveProperty('textContent', 'This link is invalid, expired, or already used. Request a new one.')
  expect(api.verifyEmail).toHaveBeenCalledOnce()
})
