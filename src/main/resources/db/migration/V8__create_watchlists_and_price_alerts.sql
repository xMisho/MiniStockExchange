CREATE TABLE exchange.watchlist (
    user_id BIGINT NOT NULL REFERENCES exchange.users(id) ON DELETE CASCADE,
    symbol VARCHAR(15) NOT NULL,
    company_name VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, symbol)
);
CREATE TABLE exchange.price_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES exchange.users(id) ON DELETE CASCADE,
    symbol VARCHAR(15) NOT NULL,
    direction VARCHAR(5) NOT NULL CHECK (direction IN ('ABOVE','BELOW')),
    target NUMERIC(19,4) NOT NULL CHECK (target > 0 AND target <> 'NaN'::NUMERIC),
    previous_price NUMERIC,
    last_observed_at TIMESTAMPTZ,
    triggered_at TIMESTAMPTZ,
    triggered_price NUMERIC,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX price_alerts_owner ON exchange.price_alerts(user_id, id DESC);
