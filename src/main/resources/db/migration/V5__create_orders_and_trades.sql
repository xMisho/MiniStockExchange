CREATE SEQUENCE exchange.order_priority_sequence AS BIGINT;

CREATE TABLE exchange.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES exchange.users(id),
    stock_symbol VARCHAR(20) NOT NULL REFERENCES exchange.stocks(symbol),
    side VARCHAR(4) NOT NULL CHECK (side IN ('BUY', 'SELL')),
    order_type VARCHAR(6) NOT NULL CHECK (order_type IN ('LIMIT', 'MARKET')),
    limit_price NUMERIC(19, 4),
    original_quantity INTEGER NOT NULL CHECK (original_quantity > 0),
    remaining_quantity INTEGER NOT NULL CHECK (remaining_quantity >= 0),
    filled_quantity INTEGER NOT NULL CHECK (filled_quantity >= 0),
    status VARCHAR(16) NOT NULL CHECK (status IN ('OPEN', 'PARTIALLY_FILLED', 'FILLED', 'CANCELLED')),
    priority_sequence BIGINT NOT NULL DEFAULT nextval('exchange.order_priority_sequence')
        UNIQUE CHECK (priority_sequence > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    CONSTRAINT orders_price_matches_type CHECK (
        (order_type = 'LIMIT' AND limit_price IS NOT NULL AND limit_price > 0 AND limit_price <> 'NaN'::NUMERIC)
        OR (order_type = 'MARKET' AND limit_price IS NULL)
    ),
    CONSTRAINT orders_status_matches_quantities CHECK (
        (status = 'OPEN' AND filled_quantity = 0 AND remaining_quantity > 0)
        OR (status = 'PARTIALLY_FILLED' AND filled_quantity > 0 AND remaining_quantity > 0)
        OR (status = 'FILLED' AND filled_quantity > 0 AND remaining_quantity = 0)
        OR (status = 'CANCELLED' AND remaining_quantity > 0)
    ),
    CONSTRAINT orders_timestamp_order CHECK (updated_at >= created_at),
    CONSTRAINT orders_trade_reference UNIQUE (id, stock_symbol, side)
);

CREATE INDEX orders_user_history ON exchange.orders(user_id, id);
CREATE INDEX orders_restoration ON exchange.orders(stock_symbol, priority_sequence)
    WHERE order_type = 'LIMIT' AND status IN ('OPEN', 'PARTIALLY_FILLED');

CREATE TABLE exchange.trades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_symbol VARCHAR(20) NOT NULL REFERENCES exchange.stocks(symbol),
    buy_order_id BIGINT NOT NULL,
    sell_order_id BIGINT NOT NULL,
    execution_price NUMERIC(19, 4) NOT NULL CHECK (execution_price > 0 AND execution_price <> 'NaN'::NUMERIC),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    executed_at TIMESTAMPTZ NOT NULL,
    buy_side VARCHAR(4) GENERATED ALWAYS AS ('BUY'::VARCHAR(4)) STORED NOT NULL,
    sell_side VARCHAR(4) GENERATED ALWAYS AS ('SELL'::VARCHAR(4)) STORED NOT NULL,
    CONSTRAINT trades_distinct_orders CHECK (buy_order_id <> sell_order_id),
    CONSTRAINT trades_buy_order FOREIGN KEY (buy_order_id, stock_symbol, buy_side)
        REFERENCES exchange.orders(id, stock_symbol, side),
    CONSTRAINT trades_sell_order FOREIGN KEY (sell_order_id, stock_symbol, sell_side)
        REFERENCES exchange.orders(id, stock_symbol, side)
);

CREATE INDEX trades_stock_history ON exchange.trades(stock_symbol, id);
CREATE INDEX trades_buy_order ON exchange.trades(buy_order_id);
CREATE INDEX trades_sell_order ON exchange.trades(sell_order_id);
